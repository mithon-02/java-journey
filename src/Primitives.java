public class Primitives {
    public static void main(String[] args) {

        System.out.println("Here we learn about the Primitive Data type..");
        // primitive Data type should unbreakable.
        int age = 24; //Primitives
        float pi = 3.1416F; //Primitive, the reason to add F, by default decimal value added in the double datatype adding F it more specific that it is the float value.
        double random = 6.382365283; //Primitive
        long largeInteger = 374348509234893654L; //Primitive, the reason to add L, by default long value added in the int datatype adding F it more specific that it is the long value.
        char star = '*'; //Primitive
        boolean check = true; //Primitive
        boolean check2 = false; //Primitive






    }
}
